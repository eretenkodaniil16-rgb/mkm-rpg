package com.eretenkodaniil.mkm.abilities;

/**
 * Stable school taxonomy. NONE is required for martial/passive ability records;
 * school membership is descriptive, never permission to execute an effect.
 */
public enum SpellSchool {
    NONE,
    RESTORATION,
    EVOCATION,
    ABJURATION,
    CONJURATION,
    TRANSMUTATION,
    ILLUSION,
    ENCHANTMENT,
    NECROMANCY,
    DIVINATION
}
